namespace {
using namespace Luau;

struct Diagnostic {
  Location location;
  std::string message;
};

[[noreturn]] void reject(const AstNode &node, std::string message) {
  throw Diagnostic{node.location, std::move(message)};
}

bool isNumber(const AstType *type) {
  const auto *reference = type ? type->as<AstTypeReference>() : nullptr;
  return reference && !reference->prefix && !reference->hasParameterList &&
         reference->name == "number";
}

class Generator {
public:
  std::string generate(const AstStatBlock &module) {
    if (module.body.size != 2)
      reject(module, "expected a local function followed by its export");
    const auto *declaration = module.body.data[0]->as<AstStatLocalFunction>();
    const auto *exportStatement = module.body.data[1]->as<AstStatReturn>();
    if (!declaration)
      reject(*module.body.data[0], "expected a local function");
    const auto *exported =
        exportStatement && exportStatement->list.size == 1
            ? exportStatement->list.data[0]->as<AstExprLocal>()
            : nullptr;
    if (!exported || exported->local != declaration->name)
      reject(*module.body.data[1], "expected return of the local function");

    const auto &function = *declaration->func;
    if (function.vararg || function.generics.size ||
        function.genericPacks.size || function.attributes.size)
      reject(function,
             "function attributes, generics and varargs are unsupported");
    const auto *returns =
        function.returnAnnotation
            ? function.returnAnnotation->as<AstTypePackExplicit>()
            : nullptr;
    if (!returns || returns->typeList.tailType || !returns->typeList.types.size)
      reject(function, "expected an explicit number return type or tuple");
    for (const auto *type : returns->typeList.types)
      if (!isNumber(type))
        reject(*type, "expected number return type");
    returnCount = returns->typeList.types.size;

    output << "// Generated by sinen_luau_to_cpp.\n#pragma once\n"
              "#include <algorithm>\n#include <cmath>\n#include <limits>\n"
              "#include <tuple>\n\nnamespace sinen::generated {\ninline ";
    if (returnCount == 1) {
      output << "double";
    } else {
      output << "std::tuple<double";
      for (size_t i = 1; i < returnCount; ++i)
        output << ", double";
      output << '>';
    }
    output << " run(";
    for (size_t i = 0; i < function.args.size; ++i) {
      const auto *arg = function.args.data[i];
      if (!isNumber(arg->annotation))
        throw Diagnostic{arg->location,
                         "expected a number parameter annotation"};
      if (i)
        output << ", ";
      output << "double " << bind(*arg);
    }
    output << ") {\n";
    if (!block(*function.body, 1))
      reject(function, "every path must return explicitly");
    output << "}\n} // namespace sinen::generated\n";
    return output.str();
  }

private:
  enum class Type { Number, Boolean };

  std::string bind(const AstLocal &local) {
    return locals.emplace(&local, "v" + std::to_string(locals.size()))
        .first->second;
  }

  static const AstExprIndexName *mathMember(const AstExpr &expr) {
    const auto *member = expr.as<AstExprIndexName>();
    const auto *global = member ? member->expr->as<AstExprGlobal>() : nullptr;
    return global && global->name == "math" ? member : nullptr;
  }

  std::string binary(const AstExprBinary &expr, Type expected) {
    using Op = AstExprBinary;
    const char *op;
    Type operand = Type::Number;
    Type result = Type::Boolean;
    switch (expr.op) {
    case Op::Add:
      op = "+";
      result = Type::Number;
      break;
    case Op::Sub:
      op = "-";
      result = Type::Number;
      break;
    case Op::Mul:
      op = "*";
      result = Type::Number;
      break;
    case Op::Div:
      op = "/";
      result = Type::Number;
      break;
    case Op::CompareEq:
      op = "==";
      break;
    case Op::CompareNe:
      op = "!=";
      break;
    case Op::CompareLt:
      op = "<";
      break;
    case Op::CompareLe:
      op = "<=";
      break;
    case Op::CompareGt:
      op = ">";
      break;
    case Op::CompareGe:
      op = ">=";
      break;
    case Op::And:
      op = "&&";
      operand = Type::Boolean;
      break;
    case Op::Or:
      op = "||";
      operand = Type::Boolean;
      break;
    default:
      reject(expr, "unsupported binary operator");
    }
    if (result != expected)
      reject(expr,
             "operator result does not match the required expression type");
    const auto left = expression(*expr.left, operand);
    const auto right = expression(*expr.right, operand);
    return "(" + left + " " + op + " " + right + ")";
  }

  std::string expression(const AstExpr &expr, Type expected) {
    if (const auto *group = expr.as<AstExprGroup>())
      return expression(*group->expr, expected);
    if (const auto *operation = expr.as<AstExprBinary>())
      return binary(*operation, expected);
    if (const auto *unary = expr.as<AstExprUnary>()) {
      if (unary->op == AstExprUnary::Op::Not && expected == Type::Boolean)
        return "(!" + expression(*unary->expr, Type::Boolean) + ")";
      if (unary->op == AstExprUnary::Op::Minus && expected == Type::Number)
        return "(-" + expression(*unary->expr, Type::Number) + ")";
    }
    if (expected == Type::Boolean) {
      if (const auto *constant = expr.as<AstExprConstantBool>())
        return constant->value ? "true" : "false";
      reject(expr, "expected a supported boolean expression");
    }
    if (const auto *constant = expr.as<AstExprConstantNumber>()) {
      if (!std::isfinite(constant->value))
        reject(expr, "expected a finite number literal");
      char buffer[64];
      const auto converted =
          std::to_chars(buffer, buffer + sizeof(buffer), constant->value,
                        std::chars_format::scientific);
      if (converted.ec != std::errc{})
        reject(expr, "could not encode number literal");
      return {buffer, converted.ptr};
    }
    if (const auto *local = expr.as<AstExprLocal>()) {
      if (const auto found = locals.find(local->local); found != locals.end())
        return found->second;
    }
    if (const auto *member = mathMember(expr);
        member && member->index == "huge")
      return "std::numeric_limits<double>::infinity()";
    if (const auto *call = expr.as<AstExprCall>();
        call && !call->self && !call->typeArguments.size) {
      if (const auto *member = mathMember(*call->func)) {
        const auto &name = member->index;
        if (call->args.size == 1 && (name == "abs" || name == "sqrt"))
          return std::string("std::") + name.value + "(" +
                 expression(*call->args.data[0], Type::Number) + ")";
        if (call->args.size == 2 && (name == "min" || name == "max")) {
          const auto first = expression(*call->args.data[0], Type::Number);
          const auto second = expression(*call->args.data[1], Type::Number);
          return std::string("(std::") + name.value + ")(" + first + ", " +
                 second + ")";
        }
      }
    }
    reject(expr, "expected a supported number expression");
  }

  bool block(const AstStatBlock &body, size_t depth) {
    bool returns = false;
    for (const auto *statement : body.body) {
      const bool statementReturns = emit(*statement, depth);
      returns = returns || statementReturns;
    }
    return returns;
  }

  bool emit(const AstStat &statement, size_t depth) {
    const std::string indent(depth * 2, ' ');
    if (const auto *local = statement.as<AstStatLocal>()) {
      if (local->vars.size != local->values.size)
        reject(statement, "locals need one numeric initializer each");
      for (size_t i = 0; i < local->vars.size; ++i) {
        const auto &var = *local->vars.data[i];
        if (var.annotation && !isNumber(var.annotation))
          reject(*var.annotation, "expected number local annotation");
        const auto value = expression(*local->values.data[i], Type::Number);
        output << indent << "const double " << bind(var) << " = " << value
               << ";\n";
      }
      return false;
    }
    if (const auto *condition = statement.as<AstStatIf>()) {
      if (condition->conditionLocal)
        reject(statement, "if local and if const are unsupported");
      output << indent << "if ("
             << expression(*condition->condition, Type::Boolean) << ") {\n";
      const bool thenReturns = block(*condition->thenbody, depth + 1);
      output << indent << "}\n";
      if (!condition->elsebody)
        return false;
      output << indent << "else {\n";
      const auto *elseBlock = condition->elsebody->as<AstStatBlock>();
      const bool elseReturns = elseBlock
                                   ? block(*elseBlock, depth + 1)
                                   : emit(*condition->elsebody, depth + 1);
      output << indent << "}\n";
      return thenReturns && elseReturns;
    }
    if (const auto *result = statement.as<AstStatReturn>()) {
      if (result->list.size != returnCount)
        reject(statement, "return value count does not match the annotation");
      output << indent << "return ";
      if (returnCount > 1)
        output << '{';
      for (size_t i = 0; i < returnCount; ++i) {
        if (i)
          output << ", ";
        output << expression(*result->list.data[i], Type::Number);
      }
      if (returnCount > 1)
        output << '}';
      output << ";\n";
      return true;
    }
    reject(statement, "unsupported statement");
  }

  std::ostringstream output;
  std::unordered_map<const AstLocal *, std::string> locals;
  size_t returnCount = 0;
};
void writeDiagnostic(std::ostream &output, std::string_view sourceName,
                     const Location &location, std::string_view message) {
  output << sourceName << ':' << location.begin.line + 1 << ':'
         << location.begin.column + 1 << ": " << message;
}
} // namespace

sinen::luau_to_cpp::Result
sinen::luau_to_cpp::convert(std::string_view source,
                            std::string_view sourceName) {
  std::ostringstream diagnostics;
  try {
    Luau::Allocator allocator;
    Luau::AstNameTable names(allocator);
    const auto parsed =
        Luau::Parser::parse(source.data(), source.size(), names, allocator);
    if (parsed.errors.empty())
      return {Generator{}.generate(*parsed.root), {}};
    for (size_t i = 0; i < parsed.errors.size(); ++i) {
      if (i)
        diagnostics << '\n';
      const auto &error = parsed.errors[i];
      writeDiagnostic(diagnostics, sourceName, error.getLocation(),
                      error.what());
    }
  } catch (const Diagnostic &error) {
    writeDiagnostic(diagnostics, sourceName, error.location, error.message);
  }
  return {{}, diagnostics.str()};
}
